    choice = input("\nSelect mode (1/2): ")
    target_file = "Batch 1 Range (0 - 100000).csv"
    
    if choice == '1':
        validate_with_ollama(target_file)
    elif choice == '2':
        prepare_gemini_batch(target_file)
